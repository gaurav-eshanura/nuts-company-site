"""Download the three brand typefaces as local woff2 files.

Self-hosting keeps the site independent of Google Fonts at runtime and avoids a
third-party render-blocking request on every page load. Only the latin subset is
kept, since this is an English-language site.

Every request is pinned to https and to Google's font hosts, and every write is
constrained to the project's assets directory, so the script cannot be talked
into reading or writing anywhere else.
"""
import hashlib
import os
import re
import urllib.parse
import urllib.request

BUILD_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(BUILD_DIR)
OUT = os.path.join(ROOT, "assets", "fonts")
CSS_DIR = os.path.join(ROOT, "assets", "css")

ALLOWED_HOSTS = frozenset({"fonts.googleapis.com", "fonts.gstatic.com"})


def _inside(directory, path):
    """True when path resolves inside directory."""
    root = os.path.abspath(directory)
    target = os.path.abspath(path)
    return target == root or target.startswith(root + os.sep)


def fetch(url):
    """GET a Google Fonts URL, rejecting anything off the allowlist."""
    parts = urllib.parse.urlparse(url)
    if parts.scheme != "https":
        raise ValueError(f"refusing non-https URL: {url}")
    if parts.hostname not in ALLOWED_HOSTS:
        raise ValueError(f"refusing off-allowlist host: {parts.hostname}")
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                      "AppleWebKit/537.36 (KHTML, like Gecko) "
                      "Chrome/120.0 Safari/537.36",
    })
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


os.makedirs(OUT, exist_ok=True)

# family spec -> local filename stem
FAMILIES = [
    ("Fraunces:opsz,wght@9..144,400;9..144,600;9..144,700;9..144,900", "fraunces"),
    ("Playfair+Display:wght@500;600;700;800", "playfair"),
    ("Poppins:wght@400;500;600;700", "poppins"),
]

faces_by_hash = {}
for query, stem in FAMILIES:
    css = fetch(
        f"https://fonts.googleapis.com/css2?family={query}&display=swap"
    ).decode()

    # Google's CSS emits one @font-face per unicode-range; keep latin only.
    blocks = re.findall(
        r"/\*\s*([\w\-\[\]]+)\s*\*/\s*@font-face\s*\{(.*?)\}", css, re.S
    )
    kept = 0
    for subset, body in blocks:
        if subset != "latin":
            continue
        weight = re.search(r"font-weight:\s*([\d\s]+);", body)
        weight = weight.group(1).strip().replace(" ", "-") if weight else "400"
        style = "italic" if "font-style: italic" in body else "normal"
        src = re.search(r"url\((https://[^)]+\.woff2)\)", body)
        if not src:
            continue

        data = fetch(src.group(1))
        digest = hashlib.sha256(data).hexdigest()
        family = re.search(r"font-family:\s*'([^']+)'", body).group(1)

        # Google serves one variable font per family and repeats the same URL for
        # every weight in the query. Writing each block out verbatim downloads
        # identical bytes once per weight - Fraunces and Playfair each landed four
        # times, over 300 KB of pure duplication. Keep one file per family and
        # collapse the weights into a single range declaration instead.
        if digest in faces_by_hash:
            faces_by_hash[digest][2].add(weight.replace("-", " "))
            kept += 1
            continue

        fname = f"{stem}-{weight}-{style}.woff2"
        dest = os.path.join(OUT, fname)
        if not _inside(OUT, dest):
            raise ValueError(f"refusing write outside assets/fonts: {dest}")
        with open(dest, "wb") as f:
            f.write(data)

        faces_by_hash[digest] = [family, fname, {weight.replace("-", " ")}, style]
        kept += 1
    print(f"{stem:<10} {kept} latin weight(s) -> 1 file")

faces = [list(v) for v in faces_by_hash.values()]
for f in faces:
    f[2] = sorted(f[2], key=lambda n: int(n.split()[0]))

# fonts live one directory up from the stylesheet; compute that, never hard-code
font_rel = os.path.relpath(OUT, CSS_DIR).replace(os.sep, "/")

lines = ["/* Generated by build/fetch_fonts.py - do not edit by hand. */", ""]
for family, fname, weights, style in faces:
    # A range such as "400 900" is how one variable font serves many weights.
    decl = weights[0] if len(weights) == 1 else f"{weights[0]} {weights[-1]}"
    lines += [
        "@font-face {",
        f"  font-family: '{family}';",
        f"  font-style: {style};",
        f"  font-weight: {decl};",
        "  font-display: swap;",
        f"  src: url('{font_rel}/{fname}') format('woff2');",
        "}",
        "",
    ]

css_path = os.path.join(CSS_DIR, "fonts.css")
if not _inside(CSS_DIR, css_path):
    raise ValueError("refusing to write outside assets/css")
with open(css_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

total = sum(os.path.getsize(os.path.join(OUT, f[1])) for f in faces)
print(f"\n{len(faces)} unique files, {total / 1024:.0f} KB total -> assets/fonts/, assets/css/fonts.css")
